    var SUPPORTED = ['en', 'fil', 'zh'];

    function normalise(lang) {
        if (!lang) { return 'en'; }
        var value = String(lang).toLowerCase();
        if (SUPPORTED.indexOf(value) !== -1) { return value; }
        if (value === 'tl' || value === 'ceb' || value.indexOf('fil') === 0 || value.indexOf('tag') === 0) { return 'fil'; }
        if (value.indexOf('zh') === 0 || value.indexOf('ch') === 0) { return 'zh'; }
        return 'en';
    }

    function translate(lang, key) {
        var table = DICT[lang] || DICT.en;
        if (Object.prototype.hasOwnProperty.call(table, key)) { return table[key]; }
        if (Object.prototype.hasOwnProperty.call(DICT.en, key)) { return DICT.en[key]; }
        return null;
    }

